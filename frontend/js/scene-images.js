  function tokenize(text) {
    if (!text) return [];
    return text
      .toLowerCase()
      .replace(/[^a-z0-9\u4e00-\u9fff\s_-]/g, " ")
      .split(/\s+/)
      .filter(Boolean);
  }

  function applySceneAliases(scores) {
    const merged = Object.assign({}, scores);
    Object.keys(SCENE_ALIASES).forEach(function (aliasId) {
      if (!merged[aliasId]) return;
      const targetId = SCENE_ALIASES[aliasId];
      merged[targetId] = (merged[targetId] || 0) + merged[aliasId];
      delete merged[aliasId];
    });
    return merged;
  }

  function resolveAlias(sceneId) {
    return SCENE_ALIASES[sceneId] || sceneId;
  }

  function scoreFromPrompt(prompt) {
    const scores = {};
    const tokens = tokenize(prompt);
    const blob = tokens.join(" ");

    const keywords = Object.keys(KEYWORD_SCORES).sort(function (a, b) {
      return b.length - a.length;
    });
    keywords.forEach(function (keyword) {
      if (blob.indexOf(keyword) === -1) return;
      const weights = KEYWORD_SCORES[keyword];
      Object.keys(weights).forEach(function (sceneId) {
        scores[sceneId] = (scores[sceneId] || 0) + weights[sceneId];
      });
    });

    tokens.forEach(function (token) {
      if (KEYWORD_SCORES[token]) {
        const weights = KEYWORD_SCORES[token];
        Object.keys(weights).forEach(function (sceneId) {
          scores[sceneId] = (scores[sceneId] || 0) + weights[sceneId] * 1.5;
        });
      }
    });

    return applySceneAliases(scores);
  }

  function poolPick(style, mood, nodeId) {
    const pool = (STYLE_POOLS[style] || STYLE_POOLS.urban_romance).filter(function (id) {
      return !!SCENES[id];
    });
    if (!pool.length) return STYLE_DEFAULTS[style] || "calm_meadow";
    const moodDefault = MOOD_DEFAULTS[mood];
    if (moodDefault && pool.indexOf(moodDefault) >= 0) {
      pool.splice(pool.indexOf(moodDefault), 1);
      pool.unshift(moodDefault);
    }
    let hash = 0;
    const key = (style || "") + ":" + (nodeId || "");
    for (let i = 0; i < key.length; i++) {
      hash = (hash * 31 + key.charCodeAt(i)) >>> 0;
    }
    return pool[hash % pool.length];
  }

  function buildSearchText(imagePrompt, title, sceneType, context) {
    const ctx = context && typeof context === "object" ? context : {};
    const parts = [];
    if (title && String(title).trim()) parts.push(String(title).trim());
    if (imagePrompt && String(imagePrompt).trim()) parts.push(String(imagePrompt).trim());
    const lines = ctx.lines;
    if (lines && lines.length) {
      lines.slice(0, 12).forEach(function (ln) {
        const t = ln && (ln.text || ln.line || "");
        if (t) parts.push(String(t).trim());
      });
    }
    ["setting", "era", "synopsis"].forEach(function (key) {
      if (ctx[key] && String(ctx[key]).trim()) parts.push(String(ctx[key]).trim());
    });
    if (parts.length && sceneType) {
      const hint = SCENE_TYPE_HINTS[(sceneType || "buildup").toLowerCase()];
      if (hint) parts.push(hint);
    }
    return parts.join(" ").trim();
  }

  function detectPeriodFiction(text) {
    const blob = (text || "").toLowerCase();
    if (!blob) return false;
    const modern = /现代|当代|21世纪|上海|北京|地铁|手机|总裁|校园|大学|赛博|cyber/.test(blob);
    const eraStrong = /十九世纪|19th|maupassant|莫泊桑|belle.?époque|1880|1890|1870/.test(blob);
    if (modern) return eraStrong;
    if (eraStrong) return true;
    const periodSoft = /舞会|舞厅|gala|项链|necklace|jewel|当铺|寒舍|陋室|garret|部长|victorian|charity gala|晚宴|soirée|soiree/.test(blob);
    const parisCue = /paris street|塞纳河|塞纳河畔|seine river/.test(blob) || (/巴黎|塞纳/.test(blob) && periodSoft);
    if (parisCue && periodSoft) return true;
    let cluster = 0;
    if (/舞会|舞厅|ballroom|gala|晚宴|soirée|soiree/.test(blob)) cluster += 1;
    if (/宴会|banquet|婚宴|酒席/.test(blob)) cluster += 1;
    if (/项链|necklace|钻石|jewel|珠宝|首饰/.test(blob)) cluster += 1;
    if (cluster >= 2) return true;
    if (/寒舍|陋室|garret|modest apartment|small apartment|阁楼/.test(blob) && cluster >= 1) return true;
    return false;
  }

  function resolve(mood, style, imagePrompt, context) {
    const ctx = context && typeof context === "object" ? context : {};
    const moodKey = (mood || "neutral").toLowerCase();
    const nodeId = ctx.nodeId || ctx.id || "";
    const avoidPath = ctx.avoid_bg_path || ctx.avoidBgPath || "";

    if (ctx.bg_path) {
      const fromPath = String(ctx.bg_path);
      const sceneId = ctx.scene_id || ctx.sceneId || "";
      return {
        sceneId: sceneId,
        path: fromPath.indexOf("?v=") >= 0 ? fromPath : fromPath + "?v=" + VERSION,
        veil: MOOD_VEIL[moodKey] || MOOD_VEIL.neutral,
        mood: moodKey,
      };
    }

    const searchText = buildSearchText(imagePrompt, ctx.title, ctx.scene_type || ctx.sceneType, ctx);
    const styleKey = detectPeriodFiction(searchText) ? "period_fiction" : (style || "urban_romance");
    const scores = scoreFromPrompt(searchText);

    if (Object.keys(scores).length === 0) {
      let fallback;
      if (nodeId) {
        fallback = poolPick(styleKey, moodKey, nodeId);
      } else {
        fallback =
          MOOD_DEFAULTS[moodKey] ||
          STYLE_DEFAULTS[styleKey] ||
          poolPick(styleKey, moodKey, nodeId);
      }
      return {
        sceneId: fallback,
        path: SCENES[fallback] || SCENES.calm_meadow,
        veil: MOOD_VEIL[moodKey] || MOOD_VEIL.neutral,
        mood: moodKey,
      };
    }

    let bestId = null;
    let bestScore = -1;
    Object.keys(scores).forEach(function (id) {
      if (!SCENES[id]) return;
      let s = scores[id];
      if (MOOD_DEFAULTS[moodKey] === id) s += 2;
      if (STYLE_DEFAULTS[styleKey] === id) s += 1.5;
      if (styleKey === "period_fiction" && /city_lights|rainy_street|subway_night|cyber_city|city_park/.test(id)) {
        s -= 7;
      }
      if (avoidPath && SCENES[id] && String(SCENES[id]).split("?")[0] === String(avoidPath).split("?")[0]) {
        s -= 8;
      }
      if (s > bestScore) {
        bestScore = s;
        bestId = id;
      }
    });

    let sceneId = resolveAlias(bestId || MOOD_DEFAULTS[moodKey] || STYLE_DEFAULTS[styleKey] || "calm_meadow");
    if (nodeId && Object.keys(scores).length > 1) {
      const ranked = Object.keys(scores)
        .filter(function (id) { return !!SCENES[id]; })
        .sort(function (a, b) { return scores[b] - scores[a]; });
      const topScore = scores[ranked[0]];
      const tied = ranked.filter(function (id) { return scores[id] >= topScore - 0.5; });
      if (tied.length > 1) {
        let hash = 0;
        const key = (styleKey || "") + ":" + nodeId;
        for (let i = 0; i < key.length; i++) {
          hash = (hash * 31 + key.charCodeAt(i)) >>> 0;
        }
        sceneId = resolveAlias(tied[hash % tied.length]);
      } else if (sceneId === STYLE_DEFAULTS[styleKey] || sceneId === MOOD_DEFAULTS[moodKey]) {
        const alt = ranked.find(function (id) { return id !== sceneId; });
        if (alt) sceneId = alt;
      }
    }

    return {
      sceneId: sceneId,
      path: SCENES[sceneId] || SCENES.calm_meadow,
      veil: MOOD_VEIL[moodKey] || MOOD_VEIL.neutral,
      mood: moodKey,
    };
  }

