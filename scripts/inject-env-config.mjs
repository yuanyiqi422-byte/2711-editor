#!/usr/bin/env node
/**
 * Inject production API config into frontend before Netlify deploy.
 * Env vars (Netlify UI → Site settings → Environment variables):
 *   API_BACKEND_URL — backend origin, e.g. https://two711-editor-api.onrender.com
 *                     sets __API_BASE__ for browser direct calls (required for SSE)
 *   API_BASE_URL    — override direct API origin (skips Netlify /api proxy entirely)
 */
import { readFileSync, writeFileSync, unlinkSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const FRONTEND = join(ROOT, "frontend");
const REDIRECTS = join(FRONTEND, "_redirects");
const NETLIFY_TOML = join(ROOT, "netlify.toml");
const INJECT_MARKER = "# [injected-api-proxy]";
const DEFAULT_PRODUCTION_API = "https://two711-editor-api.onrender.com";

function stripSlash(url) {
  return (url || "").trim().replace(/\/+$/, "");
}

function escapeRegExp(text) {
  return String(text).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

const backendProxy = stripSlash(
  process.env.API_BACKEND_URL ||
    process.env.BACKEND_URL ||
    process.env.RENDER_EXTERNAL_URL ||
    (process.env.NETLIFY ? DEFAULT_PRODUCTION_API : "")
);
// Netlify /api rewrite proxy truncates long SSE streams — prefer direct backend URL.
const apiBase = stripSlash(process.env.API_BASE_URL || process.env.VITE_API_BASE || "") || backendProxy;

const envConfig = `/** Auto-generated — do not edit manually */
(function (g) {
  g.__API_BASE__ = ${JSON.stringify(apiBase)};
})(typeof window !== "undefined" ? window : globalThis);
`;

writeFileSync(join(FRONTEND, "js", "env-config.js"), envConfig, "utf8");
console.log("[inject-env-config] __API_BASE__ =", apiBase || "(empty → same-origin /api)");

function stripInjectedProxyBlocks(content) {
  const markerEscaped = escapeRegExp(INJECT_MARKER);
  const blockRe = new RegExp(
    "\\n?" + markerEscaped + "[\\s\\S]*?(?=\\n(?:\\[\\[redirects\\]\\]|" + markerEscaped + "|\\[build\\]|\\[headers\\]|$))",
    "g"
  );
  let next = content;
  let prev;
  do {
    prev = next;
    next = next.replace(blockRe, "\n");
  } while (next !== prev);
  const apiBlockRe =
    /\n\[\[redirects\]\]\r?\n  from = "\/api\/\*"[\s\S]*?force = true\r?\n/g;
  next = next.replace(apiBlockRe, "\n");
  return next.replace(/\n{3,}/g, "\n\n");
}

function updateNetlifyToml(proxyUrl) {
  if (!existsSync(NETLIFY_TOML)) return;
  let content = stripInjectedProxyBlocks(readFileSync(NETLIFY_TOML, "utf8"));

  if (proxyUrl && !apiBase) {
    const block =
      "\n" + INJECT_MARKER + " — auto-generated by inject-env-config.mjs; do not edit by hand\n" +
      "[[redirects]]\n" +
      '  from = "/api/*"\n' +
      `  to = "${proxyUrl}/api/:splat"\n` +
      "  status = 200\n" +
      "  force = true\n";
    const spaAnchor = '[[redirects]]\r\n  from = "/*"';
    const spaAnchorLf = '[[redirects]]\n  from = "/*"';
    if (content.includes(spaAnchorLf)) {
      content = content.replace(spaAnchorLf, block.trim() + "\n\n" + spaAnchorLf);
    } else if (content.includes(spaAnchor)) {
      content = content.replace(spaAnchor, block.trim() + "\r\n\r\n" + spaAnchor);
    } else {
      content += block + "\n";
    }
    console.log("[inject-env-config] netlify.toml API proxy →", proxyUrl);
  } else {
    console.log("[inject-env-config] removed netlify.toml API proxy block");
  }
  writeFileSync(NETLIFY_TOML, content, "utf8");
}

if (backendProxy && !apiBase) {
  const redirects = `/api/*  ${backendProxy}/api/:splat  200!\n`;
  writeFileSync(REDIRECTS, redirects, "utf8");
  console.log("[inject-env-config] _redirects proxy →", backendProxy);
  updateNetlifyToml(backendProxy);
} else {
  if (existsSync(REDIRECTS)) {
    try {
      unlinkSync(REDIRECTS);
      console.log("[inject-env-config] removed stale _redirects");
    } catch {
      /* ignore */
    }
  }
  updateNetlifyToml("");
  if (!apiBase && !backendProxy) {
    console.warn(
      "[inject-env-config] WARN: no API_BACKEND_URL or API_BASE_URL — /api/* will 404 on Netlify until backend is deployed."
    );
  }
}
